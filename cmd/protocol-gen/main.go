func write(path, header string, types []any) {
	var b strings.Builder
	b.WriteString(header)
	for _, value := range types {
		t := reflect.TypeOf(value)
		fmt.Fprintf(&b, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			field := t.Field(i)
			parts := strings.Split(field.Tag.Get("json"), ",")
			if parts[0] == "-" {
				continue
			}
			optional := ""
			for _, part := range parts[1:] {
				if part == "omitempty" {
					optional = "?"
				}
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", parts[0], optional, ts(field.Type))
		}
		b.WriteString("}\n\n")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, []byte(b.String()), 0644); err != nil {
		panic(err)
	}
}
func ts(t reflect.Type) string {
	if t == reflect.TypeOf(json.RawMessage{}) {
		return "unknown"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Int32, reflect.Uint, reflect.Float64:
		return "number"
	case reflect.Slice:
		return ts(t.Elem()) + "[]"
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("protocol map keys must be strings")
		}
		return "Record<string, " + ts(t.Elem()) + ">"
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.Struct:
		return t.Name()
	default:
		panic("unsupported protocol type: " + t.String())
	}
}
